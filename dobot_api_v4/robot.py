"""Unified high-level façade for Dobot V4 robots.

All public dashboard commands are forwarded as one-liner methods directly on
:class:`DobotRobot`, providing full IDE autocompletion and static type
checking.  The forwarding region is auto-generated — to regenerate it after
the dashboard API changes, run::

    python -m dobot_api_v4._codegen

Methods that compose multiple sub-objects (lifecycle, error convenience,
feedback convenience) are defined directly on this class."""

